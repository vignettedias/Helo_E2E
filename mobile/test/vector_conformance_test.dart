/// Cross-implementation conformance tests.
///
/// THIS IS THE MOST IMPORTANT TEST FILE IN THE FLUTTER CLIENT.
///
/// A second implementation of a cryptographic protocol is rarely wrong in a way
/// that crashes. It is wrong in a way that derives a DIFFERENT KEY while
/// looking perfectly healthy in isolation — a swapped DH order, a missing 0xFF
/// prefix, a differing HKDF info string, big-endian versus little-endian
/// counters. Alice-talks-to-Alice tests in Dart cannot catch any of that,
/// because both sides would share the same defect.
///
/// These tests replay the vectors generated by the normative Python reference
/// (`scripts/generate_test_vectors.py`). If a single derived byte differs, they
/// fail. Passing them is what licenses the claim that the Dart client and the
/// reference speak the same protocol rather than two dialects of it.
///
/// Run:  flutter test
library;

import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:helo/crypto/encoding.dart';
import 'package:helo/crypto/errors.dart';
import 'package:helo/crypto/identity.dart';
import 'package:helo/crypto/prekeys.dart';
import 'package:helo/crypto/primitives.dart';
import 'package:helo/crypto/ratchet.dart';
import 'package:helo/crypto/x3dh.dart';

late Map<String, dynamic> vectors;

Map<String, dynamic> _map(Object? v) {
  if (v is! Map<String, dynamic>) {
    throw StateError('expected an object in the vector file');
  }
  return v;
}

List<Object?> _list(Object? v) {
  if (v is! List<Object?>) {
    throw StateError('expected a list in the vector file');
  }
  return v;
}

String _str(Object? v) {
  if (v is! String) throw StateError('expected a string in the vector file');
  return v;
}

int _int(Object? v) {
  if (v is! int) throw StateError('expected an int in the vector file');
  return v;
}

void main() {
  setUpAll(() {
    final File file = File('../tests/vectors/helo_vectors.json');
    if (!file.existsSync()) {
      throw StateError(
        'Vector file missing. Generate it first:\n'
        '  python3 scripts/generate_test_vectors.py',
      );
    }
    vectors = _map(jsonDecode(file.readAsStringSync()));
  });

  group('vector metadata', () {
    test('protocol identifier matches this implementation', () {
      expect(_str(vectors['protocol']), contains('Helo/1'));
      expect(vectors['post_quantum'], isFalse,
          reason: 'no PQ primitive exists in either implementation');
    });
  });

  group('primitive conformance', () {
    test('HKDF-SHA256 matches the reference', () async {
      final Map<String, dynamic> v =
          _map(_map(vectors['primitives'])['hkdf_sha256']);
      final Uint8List got = await hkdf(
        ikm: b64d(_str(v['ikm'])),
        salt: b64d(_str(v['salt'])),
        info: b64d(_str(v['info'])),
        length: _int(v['length']),
      );
      expect(b64e(got), equals(_str(v['okm'])));
    });

    test('chain ratchet derives identical message and chain keys', () async {
      final Map<String, dynamic> v =
          _map(_map(vectors['primitives'])['chain_ratchet']);
      Uint8List ck = b64d(_str(v['initial_chain_key']));

      for (final Object? stepObj in _list(v['steps'])) {
        final Map<String, dynamic> step = _map(stepObj);
        final (Uint8List mk, Uint8List next) = await kdfChain(ck);
        ck = next;
        expect(b64e(mk), equals(_str(step['message_key'])),
            reason: 'message key diverged at step ${step['index']}');
        expect(b64e(ck), equals(_str(step['next_chain_key'])),
            reason: 'chain key diverged at step ${step['index']}');

        final (Uint8List aesKey, Uint8List nonce) = await expandMessageKey(mk);
        expect(b64e(aesKey), equals(_str(step['aes_key'])));
        expect(b64e(nonce), equals(_str(step['nonce'])),
            reason: 'derived nonce must match; a mismatch here means every '
                'message would fail to decrypt cross-implementation');
      }
    });

    test('root ratchet matches the reference', () async {
      final Map<String, dynamic> v =
          _map(_map(vectors['primitives'])['root_ratchet']);
      final (Uint8List rk, Uint8List ck) = await kdfRoot(
        b64d(_str(v['root_key'])),
        b64d(_str(v['dh_output'])),
      );
      expect(b64e(rk), equals(_str(v['new_root_key'])));
      expect(b64e(ck), equals(_str(v['new_chain_key'])));
    });

    test('AES-256-GCM decrypts the reference ciphertext', () async {
      final Map<String, dynamic> v =
          _map(_map(vectors['primitives'])['aes_256_gcm']);
      final Uint8List pt = await aes256GcmDecrypt(
        key: b64d(_str(v['key'])),
        nonce: b64d(_str(v['nonce'])),
        ciphertextAndTag: b64d(_str(v['ciphertext_with_tag'])),
        associatedData: b64d(_str(v['associated_data'])),
      );
      expect(b64e(pt), equals(_str(v['plaintext'])));
    });

    test('AES-256-GCM produces the reference ciphertext', () async {
      final Map<String, dynamic> v =
          _map(_map(vectors['primitives'])['aes_256_gcm']);
      final Uint8List ct = await aes256GcmEncrypt(
        key: b64d(_str(v['key'])),
        nonce: b64d(_str(v['nonce'])),
        plaintext: b64d(_str(v['plaintext'])),
        associatedData: b64d(_str(v['associated_data'])),
      );
      expect(b64e(ct), equals(_str(v['ciphertext_with_tag'])),
          reason: 'ciphertext layout must be ciphertext ‖ tag');
    });
  });

  group('identity conformance', () {
    Future<IdentityKeyPair> identityFrom(Map<String, dynamic> v) async {
      final KeyPairBytes sig = await ed25519FromSeed(b64d(_str(v['sig_seed'])));
      final KeyPairBytes dh = await x25519FromPrivate(b64d(_str(v['dh_priv'])));
      final Uint8List binding = await ed25519Sign(
        sig.privateKey,
        concat(<List<int>>[identityBindingContext, dh.publicKey]),
      );
      return IdentityKeyPair(
        sigSeed: sig.privateKey,
        sigPub: sig.publicKey,
        dhPriv: dh.privateKey,
        dhPub: dh.publicKey,
        bindingSig: binding,
      );
    }

    test('identities reconstruct to the reference public keys', () async {
      final Map<String, dynamic> v = _map(vectors['x3dh']);
      final IdentityKeyPair alice =
          await identityFrom(_map(v['alice_identity_private']));
      final Map<String, dynamic> expected =
          _map(v['alice_identity_public']);
      expect(b64e(alice.sigPub), equals(_str(expected['sig_pub'])));
      expect(b64e(alice.dhPub), equals(_str(expected['dh_pub'])));
    });

    test('fingerprints match the reference', () async {
      final Map<String, dynamic> v = _map(vectors['x3dh']);
      final IdentityKeyPair alice =
          await identityFrom(_map(v['alice_identity_private']));
      final Uint8List fp = await alice.public.fingerprint();
      expect(b64e(fp), equals(_str(v['alice_fingerprint'])));
    });

    test('safety number matches the reference exactly', () async {
      final Map<String, dynamic> v = _map(vectors['x3dh']);
      final IdentityKeyPair alice =
          await identityFrom(_map(v['alice_identity_private']));
      final IdentityKeyPair bob =
          await identityFrom(_map(v['bob_identity_private']));
      final String sn = await safetyNumber(alice.public, bob.public);
      expect(sn, equals(_str(v['safety_number'])),
          reason: 'a mismatch means users on different platforms would see '
              'different safety numbers and could never verify each other');
    });

    test('safety number orders fingerprints by bytes, not by base64 text',
        () async {
      // Regression: the port once sorted base64 strings. This pinned pair
      // sorts the opposite way under that rule, so it fails if it returns.
      final Map<String, dynamic> v = _map(vectors['safety_number_ordering']);
      final IdentityPublic a = IdentityPublic.fromJson(_map(v['identity_a']));
      final IdentityPublic b = IdentityPublic.fromJson(_map(v['identity_b']));
      expect(b64e(await a.fingerprint()), equals(_str(v['fingerprint_a'])));
      expect(b64e(await b.fingerprint()), equals(_str(v['fingerprint_b'])));
      expect(await safetyNumber(a, b), equals(_str(v['safety_number'])));
      expect(await safetyNumber(b, a), equals(_str(v['safety_number'])),
          reason: 'both parties must see the same number');
    });

    test('verification QR payload matches the reference', () {
      final Map<String, dynamic> v = _map(vectors['safety_number_ordering']);
      expect(
        qrPayload(IdentityPublic.fromJson(_map(v['identity_a'])),
            IdentityPublic.fromJson(_map(v['identity_b']))),
        equals(_str(v['qr_payload_a_to_b'])),
      );
    });

    test('scanned QR codes are judged exactly as the reference judges them', () {
      final Map<String, dynamic> v = _map(vectors['qr_check']);
      final IdentityPublic me = IdentityPublic.fromJson(_map(v['me']));
      final IdentityPublic peer = IdentityPublic.fromJson(_map(v['peer']));
      final List<Object?> cases = v['cases'] as List<Object?>;
      expect(cases, isNotEmpty);
      for (final Object? raw in cases) {
        final Map<String, dynamic> c = _map(raw);
        expect(checkQrPayload(_str(c['scanned']), me: me, peer: peer).wire, equals(_str(c['expected'])),
            reason: _str(c['name']));
      }
    });

    test('identity binding verifies, and a substituted key does not', () async {
      final Map<String, dynamic> v = _map(vectors['x3dh']);
      final IdentityPublic bob =
          IdentityPublic.fromJson(_map(v['bob_identity_public']));
      await bob.verifyBinding();

      final IdentityPublic tampered = IdentityPublic(
        sigPub: bob.sigPub,
        dhPub: IdentityPublic.fromJson(_map(v['alice_identity_public'])).dhPub,
        bindingSig: bob.bindingSig,
      );
      expect(
        tampered.verifyBinding(),
        throwsA(isA<SignatureVerificationError>()),
      );
    });
  });

  group('X3DH conformance', () {
    test('prekey bundle verifies against the reference identity', () async {
      final Map<String, dynamic> v = _map(vectors['x3dh']);
      final PreKeyBundle bundle =
          PreKeyBundle.fromJson(_map(v['bob_prekey_bundle']));
      await bundle.verify();
    });

    test('three-DH responder derives the reference shared secret', () async {
      final Map<String, dynamic> v = _map(vectors['x3dh']);
      final Map<String, dynamic> three = _map(v['three_dh']);

      final Map<String, dynamic> bobPriv = _map(v['bob_identity_private']);
      final KeyPairBytes sig =
          await ed25519FromSeed(b64d(_str(bobPriv['sig_seed'])));
      final KeyPairBytes dh =
          await x25519FromPrivate(b64d(_str(bobPriv['dh_priv'])));
      final Uint8List binding = await ed25519Sign(
        sig.privateKey,
        concat(<List<int>>[identityBindingContext, dh.publicKey]),
      );
      final IdentityKeyPair bob = IdentityKeyPair(
        sigSeed: sig.privateKey,
        sigPub: sig.publicKey,
        dhPriv: dh.privateKey,
        dhPub: dh.publicKey,
        bindingSig: binding,
      );

      final InitialMessageHeader header =
          InitialMessageHeader.fromJson(_map(three['initial_header']));
      final Uint8List spkPriv = b64d(_str(three['signed_prekey_private']));

      // Recompute the three DH outputs directly from pinned private keys.
      final Uint8List dh1 =
          await x25519Dh(spkPriv, header.initiatorIdentity.dhPub);
      final Uint8List dh2 = await x25519Dh(bob.dhPriv, header.ephemeralPub);
      final Uint8List dh3 = await x25519Dh(spkPriv, header.ephemeralPub);

      final Uint8List shared = await hkdf(
        ikm: concat(<List<int>>[x3dhF, dh1, dh2, dh3]),
        salt: zeroSalt,
        info: infoX3dh,
        length: rootKeyLen,
      );

      expect(b64e(shared), equals(_str(three['shared_secret'])),
          reason: 'DH ordering or KDF inputs diverge from the reference');

      expect(
        b64e(associatedData(header.initiatorIdentity, bob.public)),
        equals(_str(three['associated_data'])),
      );
      expect(
        await sessionId(
            header.initiatorIdentity, bob.public, header.ephemeralPub),
        equals(_str(three['session_id'])),
      );
      expect(three['used_one_time_prekey'], isFalse);
    });

    test('three-DH and four-DH secrets differ', () {
      final Map<String, dynamic> v = _map(vectors['x3dh']);
      expect(
        _str(_map(v['three_dh'])['shared_secret']),
        isNot(equals(_str(_map(v['four_dh'])['shared_secret']))),
        reason: 'omitting the one-time prekey must change the derived secret, '
            'not be silently ignored',
      );
    });
  });

  group('envelope and header conformance', () {
    test('reference envelopes parse and re-encode identically', () {
      final Map<String, dynamic> dr = _map(vectors['double_ratchet']);
      for (final Object? entry in _list(dr['transcript'])) {
        final Map<String, dynamic> item = _map(entry);
        final Map<String, dynamic> envJson = _map(item['envelope']);
        final RatchetHeader header =
            RatchetHeader.decode(b64d(_str(envJson['header'])));
        expect(b64e(header.encode()), equals(_str(envJson['header'])),
            reason: 'header encoding must round-trip byte-exactly');
      }
    });

    test('header rejects a low-order ratchet key', () {
      final Uint8List malicious = Uint8List(headerLen)..[0] = protocolVersion;
      // bytes 1..33 remain zero: the all-zero X25519 point.
      expect(
        () => RatchetHeader.decode(malicious),
        throwsA(isA<InvalidKeyError>()),
      );
    });

    test('header rejects trailing bytes', () async {
      final KeyPairBytes kp = await x25519Generate();
      final Uint8List encoded =
          RatchetHeader(dhPub: kp.publicKey, pn: 1, n: 1).encode();
      expect(
        () => RatchetHeader.decode(
            Uint8List.fromList(<int>[...encoded, 0])),
        throwsA(isA<InvalidEncodingError>()),
      );
    });
  });

  group('local protocol behaviour', () {
    test('full conversation with out-of-order delivery', () async {
      final IdentityKeyPair aliceId = await IdentityKeyPair.generate();
      final IdentityKeyPair bobId = await IdentityKeyPair.generate();
      final PreKeyStore bobPreKeys = PreKeyStore(bobId);
      await bobPreKeys.rotateSignedPreKey();
      final List<OneTimePreKeyPublic> otps =
          await bobPreKeys.generateOneTimePreKeys(5);

      final PreKeyBundle bundle = PreKeyBundle(
        deviceId: 'bob-device',
        identity: bobId.public,
        signedPreKey: bobPreKeys.currentSignedPreKey,
        oneTimePreKey: otps.first,
      );

      final InitiateOutcome outcome =
          await x3dhInitiate(identity: aliceId, bundle: bundle);
      final X3dhResult bobResult = await x3dhRespond(
        identity: bobId,
        prekeys: bobPreKeys,
        header: outcome.header,
      );

      expect(b64e(outcome.result.sharedSecret),
          equals(b64e(bobResult.sharedSecret)),
          reason: 'Alice and Bob must derive the same X3DH secret');

      final RatchetState alice = await initInitiator(
        sharedSecret: outcome.result.sharedSecret,
        remoteSignedPreKeyPub: bundle.signedPreKey.publicKey,
      );
      RatchetState bob = await initResponder(
        sharedSecret: bobResult.sharedSecret,
        signedPreKeyPriv:
            bobPreKeys.signedPreKeyPrivate(bundle.signedPreKey.keyId),
      );

      final Uint8List ad = outcome.result.associatedData;

      final EncryptedMessage first =
          await encrypt(alice, utf8.encode('hello bob'), ad);
      final DecryptResult r1 =
          await decrypt(bob, first.header, first.ciphertext, ad);
      bob = r1.state;
      expect(utf8.decode(r1.plaintext), equals('hello bob'));

      // Out-of-order: send four, deliver 1, 3, 2, 4.
      final List<EncryptedMessage> batch = <EncryptedMessage>[];
      for (int i = 0; i < 4; i++) {
        batch.add(await encrypt(alice, utf8.encode('m$i'), ad));
      }
      for (final int idx in <int>[0, 2, 1, 3]) {
        final DecryptResult r = await decrypt(
            bob, batch[idx].header, batch[idx].ciphertext, ad);
        bob = r.state;
        expect(utf8.decode(r.plaintext), equals('m$idx'));
      }
    });

    test('tampered ciphertext fails authentication', () async {
      final IdentityKeyPair aliceId = await IdentityKeyPair.generate();
      final IdentityKeyPair bobId = await IdentityKeyPair.generate();
      final PreKeyStore bobPreKeys = PreKeyStore(bobId);
      await bobPreKeys.rotateSignedPreKey();
      final PreKeyBundle bundle = PreKeyBundle(
        deviceId: 'bob-device',
        identity: bobId.public,
        signedPreKey: bobPreKeys.currentSignedPreKey,
      );
      final InitiateOutcome outcome =
          await x3dhInitiate(identity: aliceId, bundle: bundle);
      final X3dhResult bobResult = await x3dhRespond(
        identity: bobId,
        prekeys: bobPreKeys,
        header: outcome.header,
      );

      final RatchetState alice = await initInitiator(
        sharedSecret: outcome.result.sharedSecret,
        remoteSignedPreKeyPub: bundle.signedPreKey.publicKey,
      );
      final RatchetState bob = await initResponder(
        sharedSecret: bobResult.sharedSecret,
        signedPreKeyPriv:
            bobPreKeys.signedPreKeyPrivate(bundle.signedPreKey.keyId),
      );

      final EncryptedMessage msg =
          await encrypt(alice, utf8.encode('payload'), outcome.result.associatedData);
      final Uint8List tampered = Uint8List.fromList(msg.ciphertext);
      tampered[0] ^= 0x01;

      expect(
        decrypt(bob, msg.header, tampered, outcome.result.associatedData),
        throwsA(isA<AuthenticationError>()),
      );
    });

    test('replayed message is rejected', () async {
      final IdentityKeyPair aliceId = await IdentityKeyPair.generate();
      final IdentityKeyPair bobId = await IdentityKeyPair.generate();
      final PreKeyStore bobPreKeys = PreKeyStore(bobId);
      await bobPreKeys.rotateSignedPreKey();
      final PreKeyBundle bundle = PreKeyBundle(
        deviceId: 'bob-device',
        identity: bobId.public,
        signedPreKey: bobPreKeys.currentSignedPreKey,
      );
      final InitiateOutcome outcome =
          await x3dhInitiate(identity: aliceId, bundle: bundle);
      final X3dhResult bobResult = await x3dhRespond(
        identity: bobId,
        prekeys: bobPreKeys,
        header: outcome.header,
      );
      final RatchetState alice = await initInitiator(
        sharedSecret: outcome.result.sharedSecret,
        remoteSignedPreKeyPub: bundle.signedPreKey.publicKey,
      );
      RatchetState bob = await initResponder(
        sharedSecret: bobResult.sharedSecret,
        signedPreKeyPriv:
            bobPreKeys.signedPreKeyPrivate(bundle.signedPreKey.keyId),
      );

      final Uint8List ad = outcome.result.associatedData;
      final EncryptedMessage msg =
          await encrypt(alice, utf8.encode('once'), ad);

      final DecryptResult first =
          await decrypt(bob, msg.header, msg.ciphertext, ad);
      bob = first.state;
      expect(utf8.decode(first.plaintext), equals('once'));

      expect(
        decrypt(bob, msg.header, msg.ciphertext, ad),
        throwsA(isA<ReplayError>()),
      );
    });

    test('absurd message counter is rejected, not computed', () async {
      final IdentityKeyPair aliceId = await IdentityKeyPair.generate();
      final IdentityKeyPair bobId = await IdentityKeyPair.generate();
      final PreKeyStore bobPreKeys = PreKeyStore(bobId);
      await bobPreKeys.rotateSignedPreKey();
      final PreKeyBundle bundle = PreKeyBundle(
        deviceId: 'bob-device',
        identity: bobId.public,
        signedPreKey: bobPreKeys.currentSignedPreKey,
      );
      final InitiateOutcome outcome =
          await x3dhInitiate(identity: aliceId, bundle: bundle);
      final X3dhResult bobResult = await x3dhRespond(
        identity: bobId,
        prekeys: bobPreKeys,
        header: outcome.header,
      );
      final RatchetState alice = await initInitiator(
        sharedSecret: outcome.result.sharedSecret,
        remoteSignedPreKeyPub: bundle.signedPreKey.publicKey,
      );
      RatchetState bob = await initResponder(
        sharedSecret: bobResult.sharedSecret,
        signedPreKeyPriv:
            bobPreKeys.signedPreKeyPrivate(bundle.signedPreKey.keyId),
      );

      final Uint8List ad = outcome.result.associatedData;
      final EncryptedMessage bootstrap =
          await encrypt(alice, utf8.encode('hi'), ad);
      bob = (await decrypt(bob, bootstrap.header, bootstrap.ciphertext, ad))
          .state;

      final EncryptedMessage msg = await encrypt(alice, utf8.encode('x'), ad);
      final RatchetHeader evil = RatchetHeader(
        dhPub: msg.header.dhPub,
        pn: msg.header.pn,
        n: 4000000000,
      );
      expect(
        decrypt(bob, evil, msg.ciphertext, ad),
        throwsA(isA<TooManySkippedMessagesError>()),
      );
    });
  });
}
