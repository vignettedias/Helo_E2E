/// What each status MEANS — they are not interchangeable:
///
/// * `pending`   encrypted and queued locally; the relay has not accepted it
/// * `sent`      the relay accepted the ciphertext. This is a SERVER
///               acknowledgement only; it proves nothing about the recipient.
/// * `delivered` a recipient DEVICE decrypted it and sent back an end-to-end
///               encrypted receipt (for groups: every member's device has)
/// * `read`      a recipient opened it with read receipts enabled
///               (for groups: every member has)
/// * `failed`    could not be delivered (e.g. no recipient device accepted it)
enum MessageStatus { pending, sent, delivered, read, failed }

class ChatMessage {
  ChatMessage({
    required this.id,
    required this.convId,
    required this.author,
    required this.outgoing,
    required this.sentAt,
    this.body = '',
    this.reply,
    this.attachments = const <AttachmentRef>[],
    this.forwarded = false,
    this.viewOnce = false,
    this.burned = false,
    this.edited = false,
    this.deleted = false,
    this.system = false,
    this.expiresAt,
    this.status = MessageStatus.sent,
    Set<String>? deliveredTo,
    Set<String>? readBy,
    Map<String, String>? reactions,
    this.failureReason,
  })  : deliveredTo = deliveredTo ?? <String>{},
        readBy = readBy ?? <String>{},
        reactions = reactions ?? <String, String>{};

  final String id;
  final String convId;

  /// Username of the author — for incoming messages, as authenticated by the
  /// session, never as claimed by the payload.
  final String author;
  final bool outgoing;
  final DateTime sentAt;
  String body;
  final ReplyRef? reply;
  List<AttachmentRef> attachments;
  final bool forwarded;

  /// Sent as view-once: shown once, then erased on this device.
  final bool viewOnce;

  /// A view-once message that has been read and erased.
  bool burned;
  bool edited;
  bool deleted;

  /// A notice generated by the client ("Bob added Carol"), not a message.
  final bool system;
  DateTime? expiresAt;
  MessageStatus status;
  final Set<String> deliveredTo;
  final Set<String> readBy;

  /// username -> emoji. One reaction per person, as in most messengers.
  final Map<String, String> reactions;
  String? failureReason;

  /// What the relay actually stored for this message (Crypto X-Ray).
  WireInfo? wire;

  Map<String, Object?> toJson() => <String, Object?>{
        'id': id,
        'conv': convId,
        'author': author,
        'out': outgoing,
        'ts': sentAt.millisecondsSinceEpoch,
        'body': body,
        if (reply != null) 'reply': reply!.toJson(),
        if (attachments.isNotEmpty)
          'att': attachments.map((AttachmentRef a) => a.toJson()).toList(),
        if (forwarded) 'fwd': true,
        if (viewOnce) 'once': true,
        if (burned) 'burned': true,
        if (edited) 'edited': true,
        if (deleted) 'deleted': true,
        if (system) 'system': true,
        if (expiresAt != null) 'exp': expiresAt!.millisecondsSinceEpoch,
        'status': status.name,
        if (deliveredTo.isNotEmpty) 'dlv': deliveredTo.toList(),
        if (readBy.isNotEmpty) 'read': readBy.toList(),
        if (reactions.isNotEmpty) 'react': reactions,
        if (failureReason != null) 'fail': failureReason,
        if (wire != null) 'wire': wire!.toJson(),
      };

  static ChatMessage fromJson(Map<String, dynamic> m) => ChatMessage(
        id: m['id']! as String,
        convId: m['conv']! as String,
        author: m['author']! as String,
        outgoing: m['out']! as bool,
        sentAt: DateTime.fromMillisecondsSinceEpoch(m['ts']! as int),
        body: m['body'] as String? ?? '',
        reply: m['reply'] == null ? null : ReplyRef.fromJson(m['reply']),
        attachments: (m['att'] as List<Object?>? ?? <Object?>[])
            .map(AttachmentRef.fromJson)
            .toList(),
        forwarded: m['fwd'] == true,
        viewOnce: m['once'] == true,
        burned: m['burned'] == true,
        edited: m['edited'] == true,
        deleted: m['deleted'] == true,
        system: m['system'] == true,
        expiresAt: m['exp'] == null
            ? null
            : DateTime.fromMillisecondsSinceEpoch(m['exp']! as int),
        status: MessageStatus.values.firstWhere(
            (MessageStatus s) => s.name == m['status'],
            orElse: () => MessageStatus.sent),
        deliveredTo: ((m['dlv'] as List<Object?>?) ?? <Object?>[]).cast<String>().toSet(),
        readBy: ((m['read'] as List<Object?>?) ?? <Object?>[]).cast<String>().toSet(),
        reactions: ((m['react'] as Map<String, dynamic>?) ?? <String, dynamic>{})
            .map((String k, dynamic v) => MapEntry<String, String>(k, v as String)),
        failureReason: m['fail'] as String?,
      )..wire = WireInfo.fromJson(m['wire']);
}

/// Local view of a group. Changes are accepted only under the rules in
/// groups.dart; this class just holds the current snapshot.
/// An invite link an admin created. Kept ONLY on that admin's device: the
/// secret is never part of the group snapshot, so other members cannot see or
/// use it, and revoking is just forgetting it.
class GroupInvite {
  GroupInvite({required this.secret, required this.createdMs, required this.expiresMs, this.uses = 0});

  /// How long a link works, and how many people can join with it.
  static const Duration lifetime = Duration(days: 7);
  static const int maxUses = 50;

  final String secret; // 128-bit, hex
  final int createdMs;
  final int expiresMs;
  int uses;

  bool usableAt(DateTime now) => now.millisecondsSinceEpoch < expiresMs && uses < maxUses;

  Map<String, Object?> toJson() =>
      <String, Object?>{'secret': secret, 'created': createdMs, 'expires': expiresMs, 'uses': uses};

  static GroupInvite fromJson(Map<String, dynamic> m) => GroupInvite(
        secret: m['secret'] as String,
        createdMs: m['created'] as int,
        expiresMs: m['expires'] as int,
        uses: m['uses'] as int? ?? 0,
      );
}

class GroupState {
  GroupState({
    required this.gid,
    required this.version,
    required this.name,
    required this.members,
    required this.admins,
    this.avatar,
    this.removed = false,
  });

  final String gid;
  int version;
  String name;
  List<String> members;
  List<String> admins;
  Uint8List? avatar;

  /// True once this device's user is no longer a member: the conversation
  /// stays readable but nothing more is sent or accepted.
  bool removed;

  /// Invite links created on THIS device (local only, never sent).
  List<GroupInvite> invites = <GroupInvite>[];

  GroupSnapshot toSnapshot() => GroupSnapshot(
        gid: gid, version: version, name: name,
        members: List<String>.of(members), admins: List<String>.of(admins), avatar: avatar,
      );

  static GroupState fromSnapshot(GroupSnapshot s) => GroupState(
        gid: s.gid, version: s.version, name: s.name,
        members: List<String>.of(s.members), admins: List<String>.of(s.admins), avatar: s.avatar,
      );

  Map<String, Object?> toJson() => <String, Object?>{
        ...toSnapshot().toJson(),
        if (removed) 'removed': true,
        if (invites.isNotEmpty) 'invites': invites.map((GroupInvite i) => i.toJson()).toList(),
      };

  static GroupState fromJson(Map<String, dynamic> m) => fromSnapshot(GroupSnapshot.fromJson(m))
    ..removed = m['removed'] == true
    ..invites = (m['invites'] as List<Object?>? ?? <Object?>[])
        .whereType<Map<String, dynamic>>()
        .map(GroupInvite.fromJson)
        .toList();
}

enum ConversationType { direct, group }

class Conversation {
  Conversation.direct(String this.peer)
      : type = ConversationType.direct,
        group = null,
        id = directId(peer);

  Conversation.group(GroupState this.group)
      : type = ConversationType.group,
        peer = null,
        id = groupId(group.gid);

  Conversation._(this.id, this.type, this.peer, this.group);

  static String directId(String username) => 'd:$username';
  static String groupId(String gid) => 'g:$gid';

  final String id;
  final ConversationType type;
  final String? peer;
  final GroupState? group;

  final List<ChatMessage> messages = <ChatMessage>[];
  bool pinned = false;
  bool archived = false;
  bool muted = false;
  int disappearingSeconds = 0;
  int unread = 0;

  /// Transient (never persisted): username -> when their typing indicator lapses.
  final Map<String, DateTime> typing = <String, DateTime>{};

  bool get isGroup => type == ConversationType.group;

  /// The usernames this conversation fans out to, excluding [me].
  List<String> recipients(String me) => isGroup
      ? group!.members.where((String u) => u != me).toList()
      : <String>[peer!];

  DateTime get lastActivity =>
      messages.isEmpty ? DateTime.fromMillisecondsSinceEpoch(0) : messages.last.sentAt;

  ChatMessage? byId(String messageId) {
    for (int i = messages.length - 1; i >= 0; i--) {
      if (messages[i].id == messageId) return messages[i];
    }
    return null;
  }

  Map<String, Object?> metaJson() => <String, Object?>{
        'id': id,
        'type': type.name,
        if (peer != null) 'peer': peer,
        if (group != null) 'group': group!.toJson(),
        'pinned': pinned,
        'archived': archived,
        'muted': muted,
        'timer': disappearingSeconds,
        'unread': unread,
      };

  static Conversation fromMetaJson(Map<String, dynamic> m) {
    final Conversation c = m['type'] == 'group'
        ? Conversation._(m['id']! as String, ConversationType.group, null,
            GroupState.fromJson(m['group']! as Map<String, dynamic>))
        : Conversation._(m['id']! as String, ConversationType.direct, m['peer']! as String, null);
    return c
      ..pinned = m['pinned'] == true
      ..archived = m['archived'] == true
      ..muted = m['muted'] == true
      ..disappearingSeconds = m['timer'] as int? ?? 0
      ..unread = m['unread'] as int? ?? 0;
  }
}

class Contact {
  Contact(this.username, {this.displayName, this.avatar, this.blocked = false});

  final String username;
  String? displayName;
  Uint8List? avatar;
  bool blocked;

  String get label => (displayName == null || displayName!.isEmpty) ? username : displayName!;

  Map<String, Object?> toJson() => <String, Object?>{
        'u': username,
        if (displayName != null) 'name': displayName,
        if (avatar != null) 'avatar': b64e(avatar!),
        if (blocked) 'blocked': true,
      };

  static Contact fromJson(Map<String, dynamic> m) => Contact(
        m['u']! as String,
        displayName: m['name'] as String?,
        avatar: m['avatar'] == null ? null : b64d(m['avatar']! as String),
        blocked: m['blocked'] == true,
      );
}

/// Settings. `showOnline` / `showLastSeen` are enforced by the relay (it is
/// the party that would reveal them); everything else is enforced here,
/// because receipts and typing events are end-to-end encrypted messages the
/// relay cannot see.
class AppSettings {
  bool readReceipts = true;
  bool typingIndicators = true;
  bool showOnline = true;
  bool showLastSeen = true;

  /// Explicit, visible downgrade switch. Off by default: sessions require the
  /// hybrid PQXDH handshake, and contacts whose devices publish no PQ prekey
  /// cannot be messaged until this is turned on.
  bool allowClassical = false;
  String theme = 'dark'; // system | light | dark (Cyberdeck defaults to the dark terminal)
  bool notifications = true;
  bool notificationPreviews = true;
  int defaultDisappearingSeconds = 0;
  String padding = 'block-256';

  Map<String, Object?> toJson() => <String, Object?>{
        'read_receipts': readReceipts,
        'typing': typingIndicators,
        'show_online': showOnline,
        'show_last_seen': showLastSeen,
        'allow_classical': allowClassical,
        'theme': theme,
        'notifications': notifications,
        'previews': notificationPreviews,
        'default_timer': defaultDisappearingSeconds,
        'padding': padding,
      };

  static AppSettings fromJson(Map<String, dynamic> m) => AppSettings()
    ..readReceipts = m['read_receipts'] as bool? ?? true
    ..typingIndicators = m['typing'] as bool? ?? true
    ..showOnline = m['show_online'] as bool? ?? true
    ..showLastSeen = m['show_last_seen'] as bool? ?? true
    ..allowClassical = m['allow_classical'] as bool? ?? false
    ..theme = m['theme'] as String? ?? 'dark'
    ..notifications = m['notifications'] as bool? ?? true
    ..notificationPreviews = m['previews'] as bool? ?? true
    ..defaultDisappearingSeconds = m['default_timer'] as int? ?? 0
    ..padding = m['padding'] as String? ?? 'block-256';
}

