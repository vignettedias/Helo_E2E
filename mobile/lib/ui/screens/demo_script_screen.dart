/// A run sheet for demonstrating HELO: the order to show things in, one line
/// to say for each, and a button that opens the right screen.
///
/// Every figure quoted here is a measured one from `research/results/*.json`
/// (see lib/research_numbers.dart, kept honest by a test), and every claim
/// points at something on screen that can be run live.
library;

import 'package:flutter/material.dart';

import '../../domain/messenger.dart';
import '../../research_numbers.dart';
import '../deck_state.dart';
import '../theme.dart';
import 'attack_screen.dart';
import 'crypto_lab_screen.dart';
import 'network_screen.dart';
import 'verification_dashboard_screen.dart';

class DemoStep {
  const DemoStep(this.title, this.say, {this.open, this.openLabel});
  final String title;
  final String say;
  final Widget Function(BuildContext)? open;
  final String? openLabel;
}

class DemoScriptScreen extends StatefulWidget {
  const DemoScriptScreen({required this.messenger, super.key});

  final Messenger messenger;

  @override
  State<DemoScriptScreen> createState() => _DemoScriptScreenState();
}

class _DemoScriptScreenState extends State<DemoScriptScreen> {
  final Set<int> _done = <int>{};

  List<DemoStep> get _steps => <DemoStep>[
        const DemoStep(
          'Two windows, two devices',
          'Each port is a separate browser origin with its own keys, so these really are two '
              'devices — not two tabs sharing a login.',
        ),
        const DemoStep(
          'Send a message',
          'The chat header shows PQ hybrid: this session was set up with X25519 AND ML-KEM-768. '
              'Breaking one of the two is not enough.',
        ),
        DemoStep(
          'Crypto X-Ray',
          'Same message, two views: what you read, and what the relay stored — ciphertext, a '
              'padded size, ratchet counters. Turn it on from here or with Ctrl+K.',
          openLabel: xrayMode.value ? 'Turn X-Ray off' : 'Turn X-Ray on',
        ),
        DemoStep(
          'Where the numbers come from',
          'Padding costs ${paddingE1['block-256']!.$2.toStringAsFixed(0)} bytes a message and cuts what '
              'one message leaks about its length from ${paddingE1['none']!.$1.toStringAsFixed(1)} bits to '
              '${paddingE1['block-256']!.$1.toStringAsFixed(2)}. The post-quantum handshake costs '
              '${(handshakeHybridMedianMs - handshakeClassicalMedianMs).toStringAsFixed(2)} ms and '
              '${firstEnvelopeHybridBytes - firstEnvelopeClassicalBytes} extra bytes on the first message. '
              'Measured, not estimated.',
          open: (BuildContext _) => const CryptoLabScreen(),
          openLabel: 'Crypto lab',
        ),
        DemoStep(
          'Run the protocol live',
          'RUN ALL builds a real session between two throwaway identities, then attacks it five ways. '
              'Every rejection is the real error from the real code.',
          open: (BuildContext _) => const CryptoLabScreen(),
          openLabel: 'Crypto lab',
        ),
        DemoStep(
          'Now make the relay hostile',
          'Arm an attack, send a message from the other window, and watch this device refuse it. '
              'The relay really does corrupt, duplicate, strip and swap — it only can because it was '
              'started with DEMO_ATTACKS=1.',
          open: (BuildContext c) => AttackScreen(messenger: widget.messenger),
          openLabel: 'Attack simulator',
        ),
        DemoStep(
          'What the relay knows',
          'Every request, its size and its timing. $relayColumnsMetadata of the relay database columns are '
              'metadata and only $relayColumnsCiphertext hold ciphertext: HELO does not pretend the server '
              'learns nothing.',
          open: (BuildContext c) => NetworkScreen(messenger: widget.messenger),
          openLabel: 'Network inspector',
        ),
        const DemoStep(
          'Verify a contact',
          'Details → Compare: 60 digits and 12 emoji, identical on both sides. Scanning their code '
              'checks both directions at once and verifies only that one device.',
        ),
        DemoStep(
          'The evidence',
          'Every security claim in the docs names the test that backs it, and this dashboard is '
              'generated by running them — not written by hand.',
          open: (BuildContext c) => VerificationDashboardScreen(relayBase: widget.messenger.relay.baseUrl),
          openLabel: 'Verification dashboard',
        ),
        const DemoStep(
          'Say the limits out loud',
          'Post-quantum covers session setup, not the ratchet. The relay still sees who talks to whom '
              'and when. No independent audit. Those are in the docs too.',
        ),
      ];

  @override
  Widget build(BuildContext context) {
    final HeloPalette p = HeloPalette.of(context);
    final List<DemoStep> steps = _steps;
    return Scaffold(
      appBar: AppBar(
        title: const Text('demo run sheet'),
        actions: <Widget>[
          TextButton(
            onPressed: () => setState(_done.clear),
            child: Text('Reset', style: TextStyle(color: p.textSecondary)),
          ),
        ],
      ),
      body: Center(
        child: ConstrainedBox(
          constraints: const BoxConstraints(maxWidth: 820),
          child: ListView.builder(
            padding: const EdgeInsets.all(16),
            itemCount: steps.length + 1,
            itemBuilder: (BuildContext context, int i) {
              if (i == steps.length) {
                return Padding(
                  padding: const EdgeInsets.only(top: 16),
                  child: Text(
                    '${_done.length}/${steps.length} covered · about 5 minutes end to end',
                    style: TextStyle(color: p.textFaint, fontSize: 12),
                  ),
                );
              }
              final DemoStep s = steps[i];
              final bool done = _done.contains(i);
              return Card(
                child: Padding(
                  padding: const EdgeInsets.fromLTRB(12, 10, 12, 10),
                  child: Row(crossAxisAlignment: CrossAxisAlignment.start, children: <Widget>[
                    Checkbox(
                      value: done,
                      onChanged: (bool? v) => setState(() => v == true ? _done.add(i) : _done.remove(i)),
                    ),
                    Expanded(
                      child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: <Widget>[
                        Text('${i + 1}. ${s.title}',
                            style: TextStyle(
                                fontWeight: FontWeight.w700,
                                color: done ? p.textFaint : p.textPrimary)),
                        const SizedBox(height: 4),
                        Text(s.say, style: TextStyle(color: p.textSecondary, fontSize: 12.5, height: 1.45)),
                        if (s.openLabel != null)
                          Padding(
                            padding: const EdgeInsets.only(top: 6),
                            child: OutlinedButton(
                              onPressed: () {
                                if (s.open != null) {
                                  Navigator.of(context)
                                      .push(MaterialPageRoute<void>(builder: s.open!));
                                } else {
                                  setState(() => xrayMode.value = !xrayMode.value);
                                }
                                setState(() => _done.add(i));
                              },
                              child: Text(s.openLabel!, style: const TextStyle(fontSize: 12)),
                            ),
                          ),
                      ]),
                    ),
                  ]),
                ),
              );
            },
          ),
        ),
      ),
    );
  }
}
